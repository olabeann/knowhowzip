  function policyRoute(policy){
    return `${pageLabel()} > ${policy.title}`;
  }

  function publicPolicyUrl(){
    const source=new URL(location.href);
    const hash=source.hash;
    const hashRoute=hash.replace(/^#/,"");
    let path=source.pathname.replace(/^\/+/,"");
    if(source.protocol==="file:"){
      const match=decodeURIComponent(source.pathname).match(/(?:^|\/)(knowhowzip-site\/[^?#]+)$/);
      path=match?match[1]:"knowhowzip-site/index.html";
    }else if(source.hostname==="olabeann.github.io"){
      path=path.replace(/^knowhowzip\//,"");
    }
    if(!path.startsWith("knowhowzip-site/"))path=`knowhowzip-site/${path.split("/").pop()||"index.html"}`;
    const url=new URL(path,PUBLIC_SITE_BASE);
    source.searchParams.forEach((value,key)=>{
      if(key!=="policy"&&key!=="focus")url.searchParams.set(key,value);
    });
    url.searchParams.set("policy","1");
    if(activePolicy)url.searchParams.set("focus",activePolicy.id);
    if(page==="creator-admin"&&hashRoute)url.searchParams.set("admin_view",hashRoute);
    if(page==="public"&&hashRoute.startsWith("/"))url.searchParams.set("public_route",hashRoute);
    url.hash=hash;
    return url.href;
  }

  function policyPageUrl(){
    return publicPolicyUrl();
  }

  async function submitPolicyComment(event){
    event.preventDefault();
    if(!activePolicy)return;
    const form=event.currentTarget;
    const status=form.querySelector(".policy-guide-comment-status");
    const button=form.querySelector("button");
    const author=form.elements.author.value.trim();
    const comment=form.elements.comment.value.trim();
    if(!author||!comment){
      status.textContent="작성자와 댓글을 모두 입력해 주세요.";
      status.className="policy-guide-comment-status error";
      return;
    }
    if(author.length>30||comment.length>1000){
      status.textContent="작성자는 30자, 댓글은 1000자 이내로 입력해 주세요.";
      status.className="policy-guide-comment-status error";
      return;
    }
    storeAuthor(author);
    button.disabled=true;
    status.textContent="댓글을 등록하는 중입니다.";
    status.className="policy-guide-comment-status";
    const screenUrl=policyPageUrl();
    const payload={
      policy_id:activePolicy.id,
      policy_title:activePolicy.title,
      page_name:pageLabel(),
      route:policyRoute(activePolicy),
      page_url:screenUrl,
      pageUrl:screenUrl,
      screen_url:screenUrl,
      url:screenUrl,
      author_name:author,
      comment
    };
    try{
      const notifyResponse=await fetch(POLICY_COMMENT_FUNCTION_URL,{
        method:"POST",
        headers:{
          apikey:SUPABASE_ANON_KEY,
          Authorization:`Bearer ${SUPABASE_ANON_KEY}`,
          "X-Policy-Comment-Client":"knowhowzip-policy-guide",
          "Content-Type":"application/json"
        },
        body:JSON.stringify(payload)
      });
      if(!notifyResponse.ok){
        let errorMessage="comment-submit-failed";
        try{errorMessage=(await notifyResponse.json()).error||errorMessage;}catch(error){}
        throw new Error(errorMessage);
      }
      form.elements.comment.value="";
      status.textContent="댓글을 저장하고 Slack 알림을 보냈습니다.";
      status.className="policy-guide-comment-status success";
    }catch(error){
      status.textContent=`댓글 등록에 실패했습니다. ${error.message||"잠시 후 다시 시도해 주세요."}`;
      status.className="policy-guide-comment-status error";
    }finally{
      button.disabled=false;
    }
  }

  function positionPopover(anchor){
    if(!popover||!anchor)return;
    const rect=anchor.getBoundingClientRect();
    const viewport=window.visualViewport;
    const viewportLeft=viewport?.offsetLeft||0;
    const viewportTop=viewport?.offsetTop||0;
    const viewportWidth=viewport?.width||innerWidth;
    const viewportHeight=viewport?.height||innerHeight;
    const gap=14;
    popover.style.maxHeight=`${Math.max(180,viewportHeight-gap*2)}px`;
    const width=popover.offsetWidth||370;
    const height=popover.offsetHeight||280;
    const minLeft=viewportLeft+gap;
    const maxLeft=viewportLeft+viewportWidth-width-gap;
    const left=Math.max(minLeft,Math.min(maxLeft,rect.right-width));
    const below=rect.bottom+9;
    const above=rect.top-height-9;
    const minTop=viewportTop+gap;
    const maxTop=viewportTop+viewportHeight-height-gap;
    const preferredTop=below+height<=viewportTop+viewportHeight-gap?below:above;
    const top=Math.max(minTop,Math.min(maxTop,preferredTop));
    popover.style.left=`${left}px`;
    popover.style.top=`${top}px`;
    popover.style.bottom="auto";
  }

